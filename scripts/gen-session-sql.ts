/* Writes supabase/hyrox_sessions.sql from the built-in session library.
 * Run after changing lib/session-library.ts:  npx tsx scripts/gen-session-sql.ts */
import { writeFileSync } from "node:fs";
import { BUILTIN_SESSIONS } from "../lib/session-library";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows = BUILTIN_SESSIONS.map((s, i) => `  (${[
  q(s.id), "null", q(s.kind), q(s.name), `array[${s.phases.map(q).join(", ")}]::text[]`, s.minutes,
  `${q(JSON.stringify(s.blocks))}::jsonb`, `${q(JSON.stringify(s.vol || {}))}::jsonb`, s.source ? q(s.source) : "null", i,
].join(", ")})`).join(",\n");

const sql = `-- HYROX session library: long and short quality sessions and aerobic sessions.
-- Built-in sessions (user_id null) are shared and read-only; signed-in users can add their own.
-- Run in Supabase: SQL Editor -> New query -> paste -> Run. Safe to run again (it updates the built-ins).
-- Generated by scripts/gen-session-sql.ts from lib/session-library.ts.

create table if not exists public.hyrox_sessions (
  id text primary key default gen_random_uuid()::text,
  user_id uuid default auth.uid() references auth.users on delete cascade,
  kind text not null check (kind in ('quality_long', 'quality_short', 'aerobic')),
  name text not null check (char_length(name) between 1 and 80),
  phases text[] not null default '{}',
  minutes int not null default 30 check (minutes between 5 and 240),
  blocks jsonb not null,
  vol jsonb not null default '{}'::jsonb,
  source text,
  sort int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.hyrox_sessions enable row level security;

drop policy if exists "Read built-in and own sessions" on public.hyrox_sessions;
drop policy if exists "Add own sessions" on public.hyrox_sessions;
drop policy if exists "Edit own sessions" on public.hyrox_sessions;
drop policy if exists "Delete own sessions" on public.hyrox_sessions;
create policy "Read built-in and own sessions" on public.hyrox_sessions for select using (user_id is null or auth.uid() = user_id);
create policy "Add own sessions"    on public.hyrox_sessions for insert with check (auth.uid() = user_id);
create policy "Edit own sessions"   on public.hyrox_sessions for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Delete own sessions" on public.hyrox_sessions for delete using (auth.uid() = user_id);

grant select on public.hyrox_sessions to anon, authenticated;
grant insert, update, delete on public.hyrox_sessions to authenticated;

insert into public.hyrox_sessions (id, user_id, kind, name, phases, minutes, blocks, vol, source, sort) values
${rows}
on conflict (id) do update set
  kind = excluded.kind, name = excluded.name, phases = excluded.phases, minutes = excluded.minutes,
  blocks = excluded.blocks, vol = excluded.vol, source = excluded.source, sort = excluded.sort, updated_at = now();
`;
writeFileSync(new URL("../supabase/hyrox_sessions.sql", import.meta.url), sql);
console.log(`Wrote ${BUILTIN_SESSIONS.length} sessions.`);
